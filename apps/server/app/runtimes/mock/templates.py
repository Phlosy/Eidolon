"""Template Markdown artifacts per TaskKind. See docs/architecture.md §4.3."""

from datetime import UTC, datetime

from app.models.enums import ArtifactType, TaskKind
from app.runtimes.base import ProducedArtifact, TaskContext


def _header(ctx: TaskContext) -> str:
    now = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")
    return (
        f"> Task: {ctx.title} (#EID-{ctx.task_id})  \n"
        f"> Author: {ctx.employee_name} ({ctx.employee_role})  \n"
        f"> Generated: {now} by MockRuntime\n\n"
    )


def _prd(ctx: TaskContext) -> ProducedArtifact:
    content = (
        f"# PRD: {ctx.title}\n\n"
        + _header(ctx)
        + "## 1. Background\n\n"
        + (ctx.description or "（原始需求见任务描述）")
        + "\n\n## 2. Goals\n\n"
        + "- 满足订单描述中的核心诉求\n- 交付物可被 QA 验证\n\n"
        + "## 3. Scope\n\n### In Scope\n- 核心功能实现\n- 单元测试\n\n"
        + "### Out of Scope\n- 运维与部署自动化\n\n"
        + "## 4. Acceptance Criteria\n\n"
        + (ctx.acceptance_criteria or "- 功能按描述工作\n- 测试全部通过\n")
    )
    return ProducedArtifact(ArtifactType.prd.value, f"PRD: {ctx.title}", content)


def _research_report(ctx: TaskContext) -> ProducedArtifact:
    content = (
        f"# Research Report: {ctx.title}\n\n"
        + _header(ctx)
        + "## Summary\n\n对需求相关技术方案进行了调研，给出推荐选型。\n\n"
        + "## Findings\n\n"
        + "- 方案 A：实现简单，生态成熟，适合 MVP。\n"
        + "- 方案 B：扩展性强，但引入额外复杂度，暂缓。\n\n"
        + "## Recommendation\n\n采用方案 A，后续按需评估方案 B。\n\n"
        + "## Sources\n\n"
        + "- https://example.com/docs/option-a\n"
        + "- https://example.com/benchmarks/a-vs-b\n"
        + "- internal://knowledge/mvp-constraints\n"
    )
    return ProducedArtifact(ArtifactType.research_report.value, f"Research: {ctx.title}", content)


def _source_code(ctx: TaskContext) -> ProducedArtifact:
    content = (
        f"# Implementation: {ctx.title}\n\n"
        + _header(ctx)
        + "## Architecture\n\n"
        + "单一模块 + 清晰函数边界；入口 `main()`，核心逻辑在 `run()`，便于测试。\n\n"
        + "## Code\n\n```python\n"
        + '"""Auto-generated by MockRuntime."""\n\n\n'
        + "def run() -> list[str]:\n"
        + '    """Core domain logic."""\n'
        + "    items: list[str] = []\n"
        + "    return items\n\n\n"
        + "def main() -> None:\n"
        + "    for item in run():\n"
        + "        print(item)\n\n\n"
        + 'if __name__ == "__main__":\n'
        + "    main()\n"
        + "```\n\n## Notes\n\n- 无外部依赖，Python 3.11+ 即可运行。\n"
    )
    return ProducedArtifact(ArtifactType.source_code.value, f"Code: {ctx.title}", content)


