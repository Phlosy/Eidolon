def _general(ctx: TaskContext) -> ProducedArtifact:
    content = f"# Output: {ctx.title}\n\n" + _header(ctx) + "任务已完成。\n"
    return ProducedArtifact(ArtifactType.other.value, f"Output: {ctx.title}", content)


_BUILDERS = {
    TaskKind.planning.value: _prd,
    TaskKind.research.value: _research_report,
    TaskKind.development.value: _source_code,
    TaskKind.testing.value: _test_report,
    TaskKind.order_review.value: _approval,
    TaskKind.final_review.value: _release,
    TaskKind.general.value: _general,
}


def build_artifact(ctx: TaskContext, behavior: str = "") -> ProducedArtifact:
    """behavior：由 app.brain.projection.behavior_block() 渲染好的投影块（调用方不做判断）。"""
    artifact = _BUILDERS.get(ctx.kind, _general)(ctx)
    if behavior:
        # §3.4 验收条件 2/4：投影必须能在产出里被机器验证到。
        artifact.content += f"\n\n## Behavior Projection\n\n{behavior}\n"
    if ctx.prior_knowledge:
        # Make learning retrieval observable in the produced artifact.
        skills = "\n".join(f"- {name}" for name in ctx.validated_skills) or "- (none validated yet)"
        topics = "\n".join(f"- {topic}" for topic in ctx.prior_knowledge)
        artifact.content += (
            "\n\n## Prior Knowledge Applied\n\n"
            f"using prior knowledge:\n{topics}\n\n## Validated Skills\n\n{skills}\n"
        )
    return artifact


def role_message(ctx: TaskContext) -> str:
    lines = {
        TaskKind.order_review.value: "审阅订单需求，评估可行性并给出审批意见。",
        TaskKind.planning.value: "拆解需求，撰写 PRD 并规划里程碑。",
        TaskKind.research.value: "调研相关技术方案，输出调研报告。",
        TaskKind.development.value: "依据 PRD 与调研结论进行开发实现。",
        TaskKind.testing.value: "依据验收标准设计并执行测试。",
        TaskKind.final_review.value: "终审交付物，决定是否发布。",
        TaskKind.general.value: "处理通用任务。",
    }
    return f"{ctx.employee_name}（{ctx.employee_role}）：{lines.get(ctx.kind, lines['general'])}"
